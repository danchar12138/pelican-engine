import { readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const lock = JSON.parse(
  await readFile(path.join(root, "package-lock.json"), "utf8"),
);
const rows: string[] = [];
for (const [location, raw] of Object.entries(lock.packages).sort(([a], [b]) =>
  a.localeCompare(b),
)) {
  if (!location) continue;
  const entry = raw as any;
  const name = location.split("node_modules/").at(-1);
  rows.push(
    `| ${name} | ${entry.version} | ${entry.license ?? "inspect upstream package"} | ${entry.dev ? "development/build/test" : "runtime"} |`,
  );
}
const text = `# Third-party notices\n\nthreecat original code is MIT. Third-party dependencies retain their own copyrights and licenses. This inventory is derived from the committed lockfile; it does not relicense dependency code.\n\n## Runtime distribution\n\nThe M0 browser bundle uses Three.js 0.187.0, MIT, copyright three.js authors. Its full license is copied into every dist as THREE-LICENSE.txt. The M0 geometry and simulation content are generated by threecat, not copied from an external asset library.\n\n## Source and development dependencies\n\nSource ZIPs do not bundle node_modules or browser binaries. npm downloads the exact locked packages, including their original license files. Optional platform packages below may not be installed on Windows. See each package's upstream source and distributed LICENSE/NOTICE for attribution details. Playwright-managed Chromium is downloaded separately and is not included in the threecat Release.\n\n| Package | Locked version | Declared license | Usage |\n| --- | --- | --- | --- |\n${rows.join("\n")}\n\nThe official Node.js distribution used by the optional Windows bootstrap is downloaded separately with checksum verification; it is not redistributed in the source or browser archives. User game code and user-provided assets have their own licenses and are not automatically MIT.\n`;
await mkdir(path.join(root, "docs"), { recursive: true });
await writeFile(path.join(root, "docs/THIRD-PARTY-NOTICES.md"), text);
console.log(
  JSON.stringify({
    status: "succeeded",
    packages: rows.length,
    artifact: "docs/THIRD-PARTY-NOTICES.md",
  }),
);
