const fs = require('node:fs');
const path = require('node:path');
const {spawnSync} = require('node:child_process');
const root = path.resolve(__dirname, '../threecat');
const args = process.argv.slice(2);
const label = args.shift();
const expectedFailure = args[0] === '--expected-failure';
if (expectedFailure) args.shift();
if (args.shift() !== '--') throw Error('Use label [--expected-failure] -- executable args');
const executable = args.shift();
const started = new Date().toISOString();
const result = spawnSync(executable, args, {cwd: root, encoding: 'utf8', env: {...process.env, FORCE_COLOR:'0'}, maxBuffer:64*1024*1024});
const stdout = result.stdout || '';
const stderr = (result.stderr || '') + (result.error ? String(result.error) : '');
fs.writeFileSync(path.join(__dirname, label+'.stdout.txt'), stdout);
fs.writeFileSync(path.join(__dirname, label+'.stderr.txt'), stderr);
const entry = {label, command: [executable,...args].map(s=>JSON.stringify(s)).join(' '), cwd:root, started, ended:new Date().toISOString(), exitCode:result.status ?? 1, ...(expectedFailure?{expectedFailure:true}:{}), stdout:label+'.stdout.txt', stderr:label+'.stderr.txt'};
fs.writeFileSync(path.join(__dirname,label+'.command.json'),JSON.stringify(entry,null,2));
fs.appendFileSync(path.join(__dirname,'commands.jsonl'),JSON.stringify(entry)+'\n');
process.stdout.write(stdout.length > 3500 ? stdout.slice(0,1800)+'\n[console abbreviated; complete stdout retained in report]\n' : stdout);
process.stderr.write(stderr);
console.log(`\n[${label}] exitCode=${entry.exitCode}; expectedFailure=${expectedFailure}`);
process.exitCode = expectedFailure ? (entry.exitCode === 0 ? 1 : 0) : entry.exitCode;
